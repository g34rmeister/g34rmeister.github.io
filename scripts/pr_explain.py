#!/usr/bin/env python3
"""Explain a pull request in plain language for reviewers and newcomers.

Reads the PR's changed files (one path per line, from the GitHub API) and prints a
Markdown comment: which lessons or pages the PR touches, what kind of change each
file is, and what a reviewer should check. No AI, no network: the mapping comes
from assets/js/course-data.js and fixed rules below.

Usage: python3 scripts/pr_explain.py changed_files.txt > comment.md
The workflow .github/workflows/pr-explainer.yml runs it on the base branch only;
file names from the PR are treated as data, never executed.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = '<!-- robosstics-pr-explainer -->'

# Files that scripts/site_sync.py or other scripts regenerate; hand edits get overwritten.
GENERATED = {'sitemap.xml', 'docs/lessons-index.md'}


def lesson_titles():
    titles = {}
    text = (ROOT / 'assets/js/course-data.js').read_text(encoding='utf-8')
    for m in re.finditer(r'\{"id": "(\d+-\d+)",.*?"title": "((?:[^"\\]|\\.)*)"', text):
        titles[m.group(1)] = json.loads('"' + m.group(2) + '"')
    return titles


def code(path):
    """Show an untrusted file name safely inside Markdown."""
    return '`' + path.replace('`', "'").replace('\n', ' ')[:200] + '`'


def describe(path, titles):
    m = re.fullmatch(r'robotics-(\d+)-(\d+)\.html', path)
    if m:
        lid = f'{m.group(1)}-{m.group(2)}'
        title = titles.get(lid)
        if title:
            return 'lesson', f'Lesson {m.group(1)}.{m.group(2)}, "{title}"'
        return 'new-lesson', f'A new lesson file ({m.group(1)}.{m.group(2)}) not yet in course-data.js'
    if re.fullmatch(r'robotics[-a-z]*\.html', path):
        return 'page', 'A course page (hub, chapter overview or extra page)'
    if path == 'assets/js/course-data.js':
        return 'data', 'Course data: objectives, key terms, minutes and quizzes'
    if path == 'assets/js/glossary-data.js':
        return 'data', 'Glossary definitions'
    if path == 'assets/js/widgets.js':
        return 'widget', 'Interactive widgets'
    if path.startswith('assets/'):
        return 'asset', 'Site styling, scripts or images'
    if path == 'docs/sources.json':
        return 'sources', 'The source registry (link status and claim checks)'
    if path in GENERATED or path == '.github/workflows/site-hygiene.yml':
        return 'generated', 'A generated file'
    if path.startswith('scripts/') or path.startswith('.github/'):
        return 'tooling', 'Site tooling or CI'
    if path.endswith('.md'):
        return 'docs', 'Documentation'
    return 'other', 'Another file'


CHECKS = {
    'lesson': ['Every new or changed claim cites a source in the References list, and the source really says it.',
               'Citations are numbered by first use (`python3 scripts/renumber_refs.py <file>` after editing them).',
               'New citations are checked and recorded in `docs/sources.json` (`sources.py check` fails otherwise).',
               'Safety content (ISO 10218/13849, e-stops, protective stops, PL/SIL) matches its source exactly.'],
    'new-lesson': ['New lessons are appended, never renumbered; they need an entry in `course-data.js`, '
                   '`scripts/site_manifest.json` and glossary terms, then `python3 scripts/site_sync.py`.'],
    'page': ['Pages keep exactly one `<h1>`, the shared head tags, the skip link and the footer credit.'],
    'data': ['Quiz answers and glossary definitions match the lesson text; bump `version` in course-data.js when quiz data changes.'],
    'widget': ['The widget shows only what its lesson says, fits a 320 px screen in light and dark mode, and works with the keyboard.',
               'Pages that load `widgets.js` get a bumped `?v=` number.'],
    'sources': ['Each recorded check names the evidence from the source, not only a verdict.'],
    'generated': ['This file is regenerated by `scripts/site_sync.py` (or another script); edit the inputs, not this file.'],
    'tooling': ['Tooling and CI changes get a closer review: they run on every pull request.'],
}

ORDER = ['lesson', 'new-lesson', 'page', 'data', 'widget', 'sources', 'asset', 'generated', 'tooling', 'docs', 'other']


def main():
    files = [l.strip() for l in Path(sys.argv[1]).read_text(encoding='utf-8').splitlines() if l.strip()]
    titles = lesson_titles()
    groups = {}
    for f in files:
        kind, what = describe(f, titles)
        groups.setdefault(kind, []).append((f, what))

    out = [MARKER, '### What this pull request changes', '']
    if not files:
        out.append('No changed files were found.')
    for kind in ORDER:
        for f, what in groups.get(kind, []):
            out.append(f'- {code(f)}: {what}')
    checks = [c for kind in ORDER for c in CHECKS.get(kind, []) if kind in groups]
    if checks:
        out += ['', '### What a reviewer checks', '']
        out += [f'- [ ] {c}' for c in dict.fromkeys(checks)]
    out += ['', 'The automatic checks (Site Sync and Site Hygiene) run on this pull request too; '
            'see `CONTRIBUTING.md` for how to run them locally.',
            '', '<sub>Posted by the robOSStics PR explainer (a fixed script, no AI). It updates this comment when the PR changes.</sub>']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
